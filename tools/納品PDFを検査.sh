#!/bin/bash
# 納品する全PDFを、まとめて検査する。
#   ① 版面外に出た文字 ② 図形に隠れた文字 ③ 文字どうしの重なり
#   ④ 旧字体・異体字・互換漢字 ⑤ 枠からのはみ出し ⑥ 日本語の字形かどうか
#
#   使い方:  bash 納品PDFを検査.sh
cd "$(dirname "$0")"
D="../_wp移行素材/★引継ぎ資料"
cd "$D" || exit 1
T=../../tools
echo "════════ ①〜④ 重なり・隠れ・旧字 ════════"
python3 "$T/文字の重なりを検査.py" "*.pdf" 2>/dev/null
echo
echo "════════ ⑤ 枠からのはみ出し ════════"
python3 "$T/枠からのはみ出しを検査.py" "*.pdf" 2>/dev/null
echo
echo "════════ ⑥ 日本語の字形か（直・真・者 などで判定） ════════"
python3 "$T/字形を検査.py" "*.pdf" 2>/dev/null
